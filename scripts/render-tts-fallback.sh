#!/usr/bin/env sh
# Re-renders src/speech/ttsFallbackClip.ts: the phrase the gateway plays into a
# call when the TTS provider fails (e.g. OpenAI 429 spend limit), so the callee
# is not left on a silent line. Rendered offline with espeak-ng and resampled
# to 8kHz mu-law by sox, i.e. exactly what Twilio's media stream wants, so the
# runtime needs no TTS provider and no extra packages.
#
# Usage: scripts/render-tts-fallback.sh ["Spoken text"]
# Needs docker (runs espeak-ng + sox in a throwaway alpine container).
set -eu
TEXT="${1:-Out of Open A I tokens.}"
OUT="$(dirname "$0")/../src/speech/ttsFallbackClip.ts"

MULAW_B64=$(docker run --rm node:22-alpine sh -c \
  'apk add -q --no-cache espeak-ng sox >/dev/null 2>&1 && espeak-ng --stdout -s 140 -v en-us "$0" | sox -t wav - -r 8000 -c 1 -e mu-law -t raw - | base64 -w0' \
  "$TEXT")

cat > "$OUT" <<TS
// Generated by scripts/render-tts-fallback.sh — do not edit by hand.
// 8kHz mono mu-law rendering of: "$TEXT"

/** What the fallback clip says (as a human would write it). */
export const TTS_FALLBACK_TEXT = 'Out of OpenAI tokens.';

const CLIP_BASE64 =
  '$MULAW_B64';

let cached: Uint8Array | null = null;

/** The pre-rendered fallback phrase as 8kHz mu-law bytes, ready for the media stream. */
export function ttsFallbackClip(): Uint8Array {
  if (!cached) cached = new Uint8Array(Buffer.from(CLIP_BASE64, 'base64'));
  return cached;
}
TS
echo "wrote $OUT ($(printf %s "$MULAW_B64" | base64 -d | wc -c) mu-law bytes)"
